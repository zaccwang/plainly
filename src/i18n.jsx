/** t('key', {n: 3}) -> string with {n} filled in; falls back to English, then the key. */
export function translate(lang, key, vars) {
  let s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export const LangContext = createContext({ lang: 'en', setLang: () => {}, t: (k, v) => translate('en', k, v) });
export const useLang = () => useContext(LangContext);

export const LANGS = [
  { id: 'en', label: 'EN', htmlLang: 'en', speech: 'en-US' },
  { id: 'zh', label: '中文', htmlLang: 'zh-CN', speech: 'zh-CN' },
  { id: 'es', label: 'ES', htmlLang: 'es', speech: 'es-US' },
];
export const LANG_IDS = LANGS.map((l) => l.id);
export const langInfo = (id) => LANGS.find((l) => l.id === id) ?? LANGS[0];

/** Language toggle. `vertical` for the narrow toolbar. */
export function LangToggle({ vertical = false }) {
  const { lang, setLang, t } = useLang();
  return (
    <div className={'seg' + (vertical ? ' seg-vertical' : '')} role="group" aria-label={t('lang.label')} data-testid="lang-toggle">
      {LANGS.map((l) => (
        <button key={l.id} type="button" lang={l.htmlLang} aria-pressed={lang === l.id} onClick={() => setLang(l.id)}>
          {l.label}
        </button>
      ))}
    </div>
  );
}
